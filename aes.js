const RCON = new Uint8Array([
  0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36,
]);

function xtime(x) {
  return ((x << 1) ^ (((x >> 7) & 1) * 0x11b)) & 0xff;
}

function subBytes(s) {
  for (let i = 0; i < 16; i++) s[i] = SBOX[s[i]];
}

function invSubBytes(s) {
  for (let i = 0; i < 16; i++) s[i] = INV_SBOX[s[i]];
}

function shiftRows(s) {
  const t = s.slice();
  s[1] = t[5];
  s[5] = t[9];
  s[9] = t[13];
  s[13] = t[1];
  s[2] = t[10];
  s[6] = t[14];
  s[10] = t[2];
  s[14] = t[6];
  s[3] = t[15];
  s[7] = t[3];
  s[11] = t[7];
  s[15] = t[11];
}

function invShiftRows(s) {
  const t = s.slice();
  s[1] = t[13];
  s[5] = t[1];
  s[9] = t[5];
  s[13] = t[9];
  s[2] = t[10];
  s[6] = t[14];
  s[10] = t[2];
  s[14] = t[6];
  s[3] = t[7];
  s[7] = t[11];
  s[11] = t[15];
  s[15] = t[3];
}

function mixColumns(st) {
  for (let c = 0; c < 4; c++) {
    const i = c * 4;
    const a0 = st[i],
      a1 = st[i + 1],
      a2 = st[i + 2],
      a3 = st[i + 3];
    st[i] = xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3;
    st[i + 1] = a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3;
    st[i + 2] = a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3);
    st[i + 3] = xtime(a0) ^ a0 ^ a1 ^ a2 ^ xtime(a3);
  }
}

function mul9(x) {
  return xtime(xtime(xtime(x))) ^ x;
}
function mul11(x) {
  return xtime(xtime(xtime(x))) ^ xtime(x) ^ x;
}
function mul13(x) {
  return xtime(xtime(xtime(x))) ^ xtime(xtime(x)) ^ x;
}
function mul14(x) {
  return xtime(xtime(xtime(x))) ^ xtime(xtime(x)) ^ xtime(x);
}

function invMixColumns(st) {
  for (let c = 0; c < 4; c++) {
    const i = c * 4;
    const a0 = st[i],
      a1 = st[i + 1],
      a2 = st[i + 2],
      a3 = st[i + 3];
    st[i] = mul14(a0) ^ mul11(a1) ^ mul13(a2) ^ mul9(a3);
    st[i + 1] = mul9(a0) ^ mul14(a1) ^ mul11(a2) ^ mul13(a3);
    st[i + 2] = mul13(a0) ^ mul9(a1) ^ mul14(a2) ^ mul11(a3);
    st[i + 3] = mul11(a0) ^ mul13(a1) ^ mul9(a2) ^ mul14(a3);
  }
}

/** @param {Uint8Array} s */
function addRoundKey(s, rk, round) {
  const o = round * 16;
  for (let i = 0; i < 16; i++) s[i] ^= rk[o + i];
}

function subWord(w) {
  return (
    ((SBOX[(w >> 24) & 0xff] << 24) |
      (SBOX[(w >> 16) & 0xff] << 16) |
      (SBOX[(w >> 8) & 0xff] << 8) |
      SBOX[w & 0xff]) >>>
    0
  );
}

function rotWord(w) {
  return ((w << 8) | (w >>> 24)) >>> 0;
}

/**
 * Expansion de clé FIPS-197.
 * @param {Uint8Array} key — 16, 24 ou 32 octets
 * @returns {{ nr: number; rk: Uint8Array }}
 */
export function aesKeyExpansion(key) {
  const nk = key.length / 4;
  if (![4, 6, 8].includes(nk)) {
    throw new Error("Clé AES : 16, 24 ou 32 octets uniquement.");
  }
  const nr = nk + 6;
  const nb = 4;
  const wCount = nb * (nr + 1);
  const w = new Uint32Array(wCount);

  for (let i = 0; i < nk; i++) {
    w[i] =
      (key[4 * i] << 24) |
      (key[4 * i + 1] << 16) |
      (key[4 * i + 2] << 8) |
      key[4 * i + 3];
    w[i] >>>= 0;
  }

  for (let i = nk; i < wCount; i++) {
    let temp = w[i - 1];
    if (i % nk === 0) {
      temp = subWord(rotWord(temp)) ^ (RCON[(i / nk - 1) | 0] << 24);
    } else if (nk > 6 && i % nk === 4) {
      temp = subWord(temp);
    }
    w[i] = (w[i - nk] ^ temp) >>> 0;
  }

  const rk = new Uint8Array(16 * (nr + 1));
  for (let i = 0; i < wCount; i++) {
    const x = w[i];
    rk[4 * i] = (x >> 24) & 0xff;
    rk[4 * i + 1] = (x >> 16) & 0xff;
    rk[4 * i + 2] = (x >> 8) & 0xff;
    rk[4 * i + 3] = x & 0xff;
  }
  return { nr, rk };
}

/** @param {Uint8Array} input — 16 octets */
/** @param {{ nr: number; rk: Uint8Array }} exp */
export function aesEncryptBlock(input, exp) {
  const s = new Uint8Array(input);
  const { nr, rk } = exp;
  addRoundKey(s, rk, 0);
  for (let round = 1; round < nr; round++) {
    subBytes(s);
    shiftRows(s);
    mixColumns(s);
    addRoundKey(s, rk, round);
  }
  subBytes(s);
  shiftRows(s);
  addRoundKey(s, rk, nr);
  return s;
}

/** Inverse Cipher (FIPS-197, Fig. 12). */
export function aesDecryptBlock(input, exp) {
  const s = new Uint8Array(input);
  const { nr, rk } = exp;
  addRoundKey(s, rk, nr);
  for (let round = nr - 1; round >= 1; round--) {
    invShiftRows(s);
    invSubBytes(s);
    addRoundKey(s, rk, round);
    invMixColumns(s);
  }
  invShiftRows(s);
  invSubBytes(s);
  addRoundKey(s, rk, 0);
  return s;
}

/** Incrémente un compteur 128 bits (big-endian), in-place. */
function incrementCounter(counter) {
  for (let i = 15; i >= 0; i--) {
    counter[i] = (counter[i] + 1) & 0xff;
    if (counter[i] !== 0) break;
  }
}

/**
 * AES-CTR : IV 16 octets aléatoires || ciphertext (même longueur que le texte).
 * @param {Uint8Array} keyBytes
 * @param {Uint8Array} plaintext
 */
export function aesCtrEncrypt(keyBytes, plaintext) {
  const exp = aesKeyExpansion(keyBytes);
  const iv = new Uint8Array(16);
  globalThis.crypto.getRandomValues(iv);
  const counter = new Uint8Array(iv);
  const out = new Uint8Array(16 + plaintext.length);
  out.set(iv, 0);
  for (let offset = 0; offset < plaintext.length; offset += 16) {
    const ks = aesEncryptBlock(counter, exp);
    const chunk = Math.min(16, plaintext.length - offset);
    for (let i = 0; i < chunk; i++) {
      out[16 + offset + i] = plaintext[offset + i] ^ ks[i];
    }
    incrementCounter(counter);
  }
  return out;
}

/**
 * @param {Uint8Array} keyBytes
 * @param {Uint8Array} blob — IV 16 || ciphertext
 */
export function aesCtrDecrypt(keyBytes, blob) {
  if (blob.length < 17) throw new Error("Données CTR trop courtes.");
  const exp = aesKeyExpansion(keyBytes);
  const counter = new Uint8Array(blob.slice(0, 16));
  const ct = blob.slice(16);
  const plain = new Uint8Array(ct.length);
  for (let offset = 0; offset < ct.length; offset += 16) {
    const ks = aesEncryptBlock(counter, exp);
    const chunk = Math.min(16, ct.length - offset);
    for (let i = 0; i < chunk; i++) {
      plain[offset + i] = ct[offset + i] ^ ks[i];
    }
    incrementCounter(counter);
  }
  return plain;
}
